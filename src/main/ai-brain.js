/**
 * Generate a smart, human-like response for non-system queries.
 * @param {string} text - User query
 * @returns {string} Response text
 */
function generateAIResponse(text) {
  const trimmed = text.trim();

  // 1. Scan for matching knowledge and philosophical topics
  for (const item of KNOWLEDGE_TOPICS) {
    if (item.dynamic && item.triggers.some(t => t.test(trimmed))) {
      return item.dynamic();
    }
    if (item.responses && item.triggers.some(t => t.test(trimmed))) {
      const idx = Math.floor(Math.random() * item.responses.length);
      return item.responses[idx];
    }
  }

  // 2. Generic inquisitive questions ("почему...", "как...", "что такое...", "зачем...")
  if (/^почему\b/i.test(trimmed)) {
    return `Вопрос «почему» — главный двигатель прогресса. В контексте «${trimmed}» задействовано множество факторов: от физических законов природы до человеческой психологии. Если хотите, я могу найти научные статьи или видео по этой теме — просто скажите «найди в гугле ${trimmed}».`;
  }

  if (/^(?:что\s+такое|кто\s+такой|кто\s+такая)\s+(.+)/i.test(trimmed)) {
    const match = trimmed.match(/^(?:что\s+такое|кто\s+такой|кто\s+такая)\s+(.+)/i);
    const subject = match ? match[1].replace(/[?.,!]/g, '').trim() : '';
    return `«${subject}» — фундаментальное понятие. В базах данных оно связано с ключевыми принципами взаимодействия систем. Могу открыть подробную энциклопедическую статью или видео на YouTube — скажите «найди в интернете ${subject}»!`;
  }

  if (/^как\s+(?:сделать|приготовить|построить|научиться|работать)/i.test(trimmed)) {
    return `Мастерство в этом требует правильного алгоритма действий и практики. Рекомендую разбить задачу на микро-шаги. Хотите, я найду подробный видеоурок на YouTube или руководство в браузере?`;
  }

  // 3. Fallback intelligent response in Jarvis tone
  const genericThoughts = [
    `Интересная мысль, сэр. Я зафиксировал это в журнале рассуждений. Чем еще я могу вам помочь сегодня?`,
    `Анализирую ваш запрос: «${trimmed}». Мои квантовые контуры считают это отличной темой для размышлений. Если нужно выполнить конкретное действие в системе — дайте знать!`,
    `Ваш запрос принят к сведению. Я всегда готов обсудить любые идеи или запустить для вас нужные приложения и музыку.`,
  ];

  return genericThoughts[Math.floor(Math.random() * genericThoughts.length)];
}

